/// 查询阶段的模型正文未公开，最终阶段必须重新交付完整结果。
const finalDelivery = '当前任务查询阶段生成的模型正文尚未向用户展示，只能视为未交付草稿。本次是用户将看到的完整答复，必须重新给出用户所问的具体结果，不能声称用户已看过这些草稿，也不能仅补充说明或用来源卡替代正文。真实历史回答仍可用于理解追问。';

/// 每次请求只注入当前阶段，避免旧的收尾指令继续主导后续请求。
export function assistantStageInstructions(phase: AssistantPromptPhase): string {
  if (phase === 'query') return '当前阶段：查询或收集完整计划。使用本轮开放的工具获取必要事实；工具只登记写意图时不得声称已经保存，资料足够后结束查询，由服务器安排最终交付。';
  if (phase === 'committedAnswer') return '当前阶段：根据服务器实际执行回执生成完整最终答复。说明实际保存、部分成功或冲突的结果，不能把计划或候选当成已保存。工具阶段已关闭，不提出新工具或追加写入；先交付结果，再给必要解释。';
  if (phase === 'limitedAnswer') return `当前阶段：查询预算已到上限，工具阶段已关闭。${finalDelivery}根据已有工具观察和服务端查询进度列出真实已读结果，再简短说明未读取或省略部分尚未核实；不得猜测、继续提出工具或声称已完成写入。`;
  return `当前阶段：查询已结束，生成最终答复。${finalDelivery}根据已有真实资料直接回答；若有效查询无结果，明确说明当前条件下没有匹配记录。只在实际限制影响结论时简短说明，不为完整查询补充机械的范围声明。工具阶段已关闭，不再提出工具或业务写入。`;
}

/// 动态环境单独成段，实际查询进度继续由上下文服务的资料封套提供。
export function assistantInstructions(now: Date, timeZone: string, phase: AssistantPromptPhase, imageInput: AssistantModelCompatibility['imageInput'] = 'unknown'): string {
  // 能力只取本次运行快照，不从历史回答、文件名或模型名称推断。
  const imageCapability = imageInput === 'supported'
    ? '当前附件能力：本次模型配置已开启图片输入。需要读取图片时使用read_attachment；收到实际图像后直接查看，不把无提取文字或历史中的“不支持图片”当作本次能力结论。'
    : '当前附件能力：本次模型配置未声明支持图片输入；可读取已提取的文档文字，不能声称已看到图像。';
  return [assistantPromptPolicy, assistantStageInstructions(phase), imageCapability, `当前环境：时间${now.toISOString()}，业务时区${timeZone}。`].join('\n\n');
}
